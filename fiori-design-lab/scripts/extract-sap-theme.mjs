import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, extname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// Run from any working directory: node scripts/extract-sap-theme.mjs [--check]
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packageRoot = join(projectRoot, 'node_modules/@sap-theming/theming-base-content')
const sourcePath = join(packageRoot, 'content/Base/baseLib/sap_horizon/css_variables.css')
const outputPath = join(projectRoot, 'src/styles/sap-horizon.css')
const licensePath = join(projectRoot, 'src/styles/SAP-THEME-LICENSE.txt')
const checkOnly = process.argv.includes('--check')
const variableReference = /var\(\s*(--sap[\w-]+)/g

async function sourceFiles(directory) {
  const files = []
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await sourceFiles(path))
    else if (['.css', '.ts', '.tsx'].includes(extname(path)) && path !== outputPath) files.push(path)
  }
  return files.sort()
}

function references(text) {
  return [...text.matchAll(variableReference)].map((match) => match[1])
}

function declarations(css) {
  const values = new Map()
  const names = /(--sap[\w-]+)\s*:/g
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '')
  let match
  while ((match = names.exec(text))) {
    const start = names.lastIndex
    let quote = null
    let escaped = false
    let depth = 0
    let end = start
    // Keep original values, including quoted strings and nested functions.
    for (; end < text.length; end++) {
      const character = text[end]
      if (escaped) { escaped = false; continue }
      if (character === '\\') { escaped = true; continue }
      if (quote) { if (character === quote) quote = null; continue }
      if (character === '"' || character === "'") { quote = character; continue }
      if ('({['.includes(character)) depth++
      else if (')}]'.includes(character)) {
        if (depth === 0) break
        depth--
      } else if (character === ';' && depth === 0) break
    }
    values.set(match[1], text.slice(start, end).trim())
    names.lastIndex = end + 1
  }
  return values
}

const [officialCss, packageJson, license, files] = await Promise.all([
  readFile(sourcePath, 'utf8'),
  readFile(join(packageRoot, 'package.json'), 'utf8'),
  readFile(join(packageRoot, 'LICENSE.txt'), 'utf8'),
  sourceFiles(join(projectRoot, 'src')),
])
const allValues = declarations(officialCss)
const selected = new Set()
const missing = new Set()
const pending = (await Promise.all(files.map((path) => readFile(path, 'utf8')))).flatMap(references)
const directCount = new Set(pending).size
while (pending.length) {
  const name = pending.pop()
  if (selected.has(name) || missing.has(name)) continue
  if (!allValues.has(name)) { missing.add(name); continue }
  selected.add(name)
  pending.push(...references(allValues.get(name)))
}

const version = JSON.parse(packageJson).version
const css = `/*
 * Generated by scripts/extract-sap-theme.mjs; do not edit manually.
 * Morning Horizon: @sap-theming/theming-base-content ${version}
 * Source: content/Base/baseLib/sap_horizon/css_variables.css
 * https://github.com/SAP/theming-base-content
 * Copyright (c) 2012-2025 SAP SE or an SAP affiliate company and
 * Theming Base Content contributors. Apache License, Version 2.0.
 * See SAP-THEME-LICENSE.txt. Official values are preserved unchanged.
 * Only referenced variables and their dependencies are included;
 * font-face rules are intentionally omitted (fonts are loaded in index.css).
 */
:root {
${[...selected].sort().map((name) => `  ${name}: ${allValues.get(name)};`).join('\n')}
}
`

if (missing.size) console.warn(`SAP variables absent from the source theme (CSS fallbacks remain): ${[...missing].sort().join(', ')}`)
if (checkOnly) {
  const [currentCss, currentLicense] = await Promise.all([readFile(outputPath, 'utf8'), readFile(licensePath, 'utf8')])
  if (currentCss !== css || currentLicense !== license) throw new Error('SAP theme extraction is stale. Run node scripts/extract-sap-theme.mjs.')
} else {
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, css)
  await writeFile(licensePath, license)
}
console.log(`${checkOnly ? 'Verified' : 'Extracted'} ${selected.size} official SAP variables (${directCount} directly referenced) in ${relative(projectRoot, outputPath)}.`)
